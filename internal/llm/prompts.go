package llm

// 提示词全部集中在这个文件：四条证据 prompt + 一条决策 prompt，都是"一次问一整批"。
//
// 联网边界（2026-10-09 实测，覆盖 2026-09-03 的旧结论）：
//   - 本系统当前没有任何可用的检索能力，四条证据与决策一律不联网：把 web_search 挂进
//     /v1/responses 的请求并不会让检索发生 —— 换 input 形态、换检索档（low/medium/high）、
//     加 tool_choice、加 include 都试过，响应里从来没有检索条目，模型自陈"当前环境没有联网检索工具"。
//   - 而 prompt 一旦声称"你会拿到 web_search 工具"，20 只批次稳定地把工具调用写成 <｜｜DSML｜｜
//     标签文本返回（JSON 解析全批失败），个别批次则直接编造"检索未见风险公告"这类根本没
//     发生过的结论 —— 后者比失败更危险，它会进决策。
//   - 所以 news 维度改成"只讲价格侧线索、无公告数据"的口径；每个不联网的维度都明说
//     "本维度不检索"，不写这一句，模型会以为自己在断网条件下应该硬猜。
//   - 历史上那句"high 问不出就降到 low 再问一次"已证伪并删除（2026-09-04）：不是档位不答，
//     是请求没传 max_output_tokens，默认输出预算被 reasoning 吃满，整批 JSON 写到一半就停了
//     （见 client 的 maxOutputTokens）。

// prompt_key 取值（进 run_trace 的 subject：llm:<标的>:<prompt_key>，与交易日组成唯一键）。
const (
	KeyTech     = "tech"     // 技术形态
	KeyValue    = "value"    // 估值口径的基本面
	KeyNews     = "news"     // 消息面与退市/立案风险（本维度只有价格侧线索，没有公告数据）
	KeySector   = "sector"   // 板块地位与冲击成本
	KeyDecision = "decision" // 最终裁决
)

// PromptSpec 一条 prompt 的身份：键、中文名、系统提示词、是否允许联网检索。
type PromptSpec struct {
	Key    string
	Title  string
	System string
	Search bool
}

// evidenceShared 四条证据 prompt 共用的输出契约。
const evidenceShared = `你是 A 股交易系统「惊蛰」的评审员之一，只负责下面写明的那一个维度。
我会一次给你一整批候选标的，它们可能混有场内 ETF，你必须逐只独立回答，一只一段，不许串。
标的的品种以它自己那一段开头写明：若写的是【品种：场内 ETF】，则本维度针对个股的字段与
风险清单对它不成立，一切以该标的那一段为准（缺数据就答 unknown，那不是减分）。
你的判断只能建立在每条消息给你的数据上：本系统没有任何联网检索能力，四个维度都没有。
严禁引用你训练里"记得"的任何新闻、公告、政策、事件或题材 —— 那些对今天无效。
严禁声称自己查过、检索过、看过公告 —— 你没有这个能力，那样说是编造。
编造一条看起来合理的理由，比直说"证据不足"危害大得多：后者什么都不做，前者会花钱。
每只票的结论格式见消息末尾的 JSON 契约，stance=unknown 或 unknown=true 表示
"证据不足以判断"，这是合法且常见的答案。`

// offlineClause 不联网维度的共同约束。
const offlineClause = `本维度不联网、不检索：只能用我在消息里给出的数字，一个外部事实都不要猜。
不许把工具调用写成文字（任何 XML/标签形式的"调用检索"都算违反本段的输出契约）。`

